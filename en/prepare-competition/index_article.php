<h6>
    POLYTECHNICAL OLYMPIAD
</h6>
<p>
    Participants: A team of three people, students in grades 7-11 of schools, first-year secondary vocational education institutions. As part of the Olympiad, participants will be offered tasks that will require knowledge in the field of electronics, design and programming; the ability to handle measuring tools and devices (rulers, calipers, multimeter, oscilloscope); skills in working with a 3D printer and software: Compass 3D, Autodesk Fusion, Arduino IDE, Visual Studio. The main areas of the Olympiad:
</p>
<ul>
    <li>3D modeling, design and 3D printing;</li>
    <li>electronics, electrical engineering, soldering of radio components;</li>
    <li>programming and algorithm development.</li>
</ul>
<br>
<h6>
    COMPETITIONS
</h6>
<p>
    It is planned to hold competitions of mobile robots and unmanned aerial vehicles, assembled both on the basis of well-known designers and having original designs.<br>MOBILE ROBOTS
</p>
<ul>
    <li>
        <b>(LL) LEGO League:</b>Fights of remotely and autonomously controlled mobile robots assembled from LEGO constructors. The overall dimensions of the robot are no more than 250x250x250 mm, weight no more than 1 kg.<br>
        <b>Participants:</b>Students in grades 5-9 of schools and institutions of additional education.
    </li>
    <li>
        <b>(L2) League 2:</b>Battles of autonomously controlled mobile robots assembled from original parts of their own manufacture or construction kits (except LEGO or its analogues). The overall dimensions of the robot are no more than 300x300x300 mm, weight no more than 2 kg.<br>
        <b>Participants:</b>Students in grades 7-11 of schools, institutions of additional, secondary vocational and higher education, teams of enterprises.
    </li>
    <li>
        (LBR) League of Combat Robots: Battles of remote-controlled mobile robots assembled from original parts of our own manufacture for destruction. Overall dimensions of the robot are no more than 250x250x250 mm, weight is no more than 1.5 kg.<br>
        <b>Participants:</b>Students in grades 7-11 of schools, institutions of additional, secondary vocational and higher education, teams of enterprises.
    </li>
</ul>
